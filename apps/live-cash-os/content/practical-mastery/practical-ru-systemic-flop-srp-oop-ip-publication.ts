function applyOptions(options: PracticalDecisionOption[], patch: Readonly<Record<string, string>>) {
  return options.map((option) => Object.hasOwn(patch, option.id)
    ? { ...option, textRu: patch[option.id] }
    : option);
}

export function applyPracticalRuSystemicFlopSrpOopIpDecisionProjection(decision: PracticalDecision): PracticalDecision {
  const patch = practicalRuSystemicFlopSrpOopIpDecisionPatches.get(decision.id);
  if (!patch) return decision;
  return {
    ...decision,
    cueRu: patch.cueRu,
    questionRu: patch.questionRu,
    explanationRu: patch.explanationRu,
    actionOptions: applyOptions(decision.actionOptions, patch.actionOptions),
    reasonOptions: applyOptions(decision.reasonOptions, patch.reasonOptions),
  };
}

