function setDrill(
  moduleId: "evidence" | "transfer",
  drillId: string,
  copy: {
    assumptions: string[];
    cue: string;
    question: string;
    actions: [string, string, string];
    reasons: [string, string, string];
    explanation: string;
  },
) {
  const drill = moduleById[moduleId].drills.find((item) => item.id === drillId);
  if (!drill) throw new Error(`Missing drill ${drillId}`);
  drill.assumptions = [...copy.assumptions];
  drill.cue = copy.cue;
  drill.question = copy.question;
  drill.actionOptions.forEach((option, index) => { option.text = copy.actions[index]; });
  drill.reasonOptions.forEach((option, index) => { option.text = copy.reasons[index]; });
  drill.explanation = copy.explanation;
}

function setCard(moduleId: "evidence" | "transfer", cardId: string, front: string, back: string) {
  const card = moduleById[moduleId].flashcards.find((item) => item.id === cardId);
  if (!card) throw new Error(`Missing card ${cardId}`);
  card.front = front;
  card.back = back;
}

