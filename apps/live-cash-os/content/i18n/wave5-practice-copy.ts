const FILTER_CARD_ID = "fil-card-blocker";

type DrillCopyPatch = Partial<{
  assumptions: string[];
  cue: string;
  question: string;
  actions: [string, string, string];
  reasons: [string, string, string];
  explanation: string;
}>;

function patchDrill(moduleId: ModuleId, drillId: string, patch: DrillCopyPatch) {
  const target = moduleById[moduleId].drills.find((item) => item.id === drillId);
  if (!target) throw new Error(`Missing learner-language drill ${drillId}`);
  if (patch.assumptions) target.assumptions = [...patch.assumptions];
  if (patch.cue) target.cue = patch.cue;
  if (patch.question) target.question = patch.question;
  if (patch.actions) target.actionOptions.forEach((option, index) => { option.text = patch.actions![index]; });
  if (patch.reasons) target.reasonOptions.forEach((option, index) => { option.text = patch.reasons![index]; });
  if (patch.explanation) target.explanation = patch.explanation;
}

function patchCard(moduleId: ModuleId, cardId: string, front: string, back: string) {
  const card = moduleById[moduleId].flashcards.find((item) => item.id === cardId);
  if (!card) throw new Error(`Missing learner-language card ${cardId}`);
  card.front = front;
  card.back = back;
}

