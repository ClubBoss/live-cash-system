function replaceStrings(target: string[], source: string[]) {
  target.splice(0, target.length, ...source);
}

function applyDrill(target: Drill, source: (typeof DRILL_COPY)[string]) {
  replaceStrings(target.assumptions, source.assumptions);
  target.cue = source.cue;
  target.question = source.question;
  target.actionOptions.forEach((option, index) => { option.text = source.actions[index]; });
  target.reasonOptions.forEach((option, index) => { option.text = source.reasons[index]; });
  target.explanation = source.explanation;
}

export function applyGeometryRuGold() {
  const target = moduleById.geometry;
  Object.assign(target, RU_COPY);
  if (target.lab.type === "spr") {
    target.lab.title = "SPR после колла";
    target.lab.description = "Укажи банк до ставки, оставшийся стек и размер ставки. Тренажёр покажет SPR после колла.";
  }
  Object.assign(target.glossary[0], {
    term: "Эффективный стек",
    meaning: "Меньший из стека Hero и стека конкретного соперника.",
  });
  Object.assign(target.glossary[1], {
    term: "SPR",
    meaning: "Отношение оставшегося стека к размеру банка.",
  });
  Object.assign(target.glossary[2], {
    term: "Рабочая ставка",
    meaning: "Обязательная ставка, относительно которой сейчас оцениваются глубина и размеры префлоп-действий.",
  });
  for (const drill of target.drills) {
    const copy = DRILL_COPY[drill.id];
    if (copy) applyDrill(drill, copy);
  }
  for (const card of target.flashcards) {
    const copy = CARD_COPY[card.id];
    if (copy) [card.front, card.back] = copy;
  }
}
